-- 운영 관리자 일별 요약 SQL.
-- 결제/배송 상태와 주문 상태를 한 화면에서 집계한다.

SELECT
    TRUNC(o.ORDERED_AT) AS ORDER_DATE,
    COUNT(*) AS ORDER_COUNT,
    SUM(o.ORDER_AMOUNT) AS ORDER_AMOUNT,
    SUM(CASE WHEN o.ORDER_STATUS = 'RECEIVED' THEN 1 ELSE 0 END) AS RECEIVED_COUNT,
    SUM(CASE WHEN o.ORDER_STATUS = 'PAID' THEN 1 ELSE 0 END) AS PAID_COUNT,
    SUM(CASE WHEN o.ORDER_STATUS IN ('READY_TO_SHIP', 'SHIPPED') THEN 1 ELSE 0 END) AS SHIPPING_COUNT,
    SUM(CASE WHEN o.ORDER_STATUS = 'DELIVERED' THEN 1 ELSE 0 END) AS DELIVERED_COUNT,
    SUM(CASE WHEN p.PAYMENT_STATUS = 'APPROVED' THEN p.PAYMENT_AMOUNT ELSE 0 END) AS APPROVED_PAYMENT_AMOUNT,
    SUM(CASE WHEN p.PAYMENT_STATUS = 'FAILED' THEN 1 ELSE 0 END) AS PAYMENT_FAILED_COUNT,
    SUM(CASE WHEN d.DELIVERY_STATUS = 'HOLD' THEN 1 ELSE 0 END) AS DELIVERY_HOLD_COUNT
FROM LEGACY_ORDER o
LEFT JOIN LEGACY_PAYMENT p
    ON p.ORDER_ID = o.ORDER_ID
LEFT JOIN LEGACY_DELIVERY d
    ON d.ORDER_ID = o.ORDER_ID
WHERE o.ORDERED_AT >= :fromDate
  AND o.ORDERED_AT < :toDate + 1
GROUP BY TRUNC(o.ORDERED_AT)
ORDER BY ORDER_DATE DESC;
