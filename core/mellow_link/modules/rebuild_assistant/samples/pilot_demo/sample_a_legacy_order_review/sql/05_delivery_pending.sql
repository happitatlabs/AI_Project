-- 배송 대기 및 지연 주문 조회 SQL.
-- 01_order_search.sql과 유사한 조인 구조가 반복된다.

SELECT
    o.ORDER_ID,
    o.ORDER_NO,
    o.ORDER_STATUS,
    o.ORDERED_AT,
    p.PAYMENT_STATUS,
    p.PAID_AT,
    d.DELIVERY_ID,
    d.DELIVERY_STATUS,
    d.READY_AT,
    d.SHIPPED_AT,
    d.RETRY_COUNT,
    d.LAST_ERROR_MESSAGE,
    CASE
        WHEN d.DELIVERY_ID IS NULL THEN 'DELIVERY_ROW_MISSING'
        WHEN d.DELIVERY_STATUS = 'WAITING' AND p.PAID_AT < SYSDATE - 1 THEN 'READY_DELAYED'
        WHEN d.DELIVERY_STATUS = 'HOLD' THEN 'MANUAL_REVIEW_REQUIRED'
        WHEN d.RETRY_COUNT >= 3 THEN 'RETRY_LIMIT_REACHED'
        ELSE 'PENDING'
    END AS PENDING_REASON
FROM LEGACY_ORDER o
JOIN LEGACY_PAYMENT p
    ON p.ORDER_ID = o.ORDER_ID
LEFT JOIN LEGACY_DELIVERY d
    ON d.ORDER_ID = o.ORDER_ID
WHERE p.PAYMENT_STATUS = 'APPROVED'
  AND o.ORDER_STATUS IN ('PAID', 'READY_TO_SHIP')
  AND (d.DELIVERY_STATUS IS NULL OR d.DELIVERY_STATUS IN ('WAITING', 'READY', 'HOLD'))
ORDER BY p.PAID_AT ASC, o.ORDER_ID ASC;
