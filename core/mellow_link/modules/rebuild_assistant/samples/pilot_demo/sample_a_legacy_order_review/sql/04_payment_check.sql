-- 결제 성공 후 주문 상태가 갱신되지 않은 대상 점검 SQL.
-- 운영자는 이 결과를 보고 수기 보정 또는 재처리 여부를 판단한다.

SELECT
    o.ORDER_ID,
    o.ORDER_NO,
    o.ORDER_STATUS,
    o.ORDER_AMOUNT,
    p.PAYMENT_ID,
    p.PAYMENT_STATUS,
    p.PAYMENT_AMOUNT,
    p.APPROVAL_NO,
    p.PAID_AT,
    p.INTERFACE_RESULT,
    p.INTERFACE_MESSAGE,
    CASE
        WHEN p.PAYMENT_STATUS = 'APPROVED'
             AND o.ORDER_STATUS = 'RECEIVED'
             THEN 'PAYMENT_APPROVED_ORDER_NOT_UPDATED'
        WHEN p.PAYMENT_STATUS = 'APPROVED'
             AND p.PAYMENT_AMOUNT <> o.ORDER_AMOUNT
             THEN 'PAYMENT_AMOUNT_MISMATCH'
        WHEN p.PAYMENT_STATUS IN ('FAILED', 'CANCELLED')
             AND o.ORDER_STATUS IN ('PAID', 'READY_TO_SHIP')
             THEN 'ORDER_STATUS_NEEDS_REVIEW'
        ELSE 'OK'
    END AS CHECK_RESULT
FROM LEGACY_ORDER o
JOIN LEGACY_PAYMENT p
    ON p.ORDER_ID = o.ORDER_ID
WHERE p.PAID_AT >= :fromDate
  AND p.PAID_AT < :toDate + 1
  AND (
      (p.PAYMENT_STATUS = 'APPROVED' AND o.ORDER_STATUS = 'RECEIVED')
      OR (p.PAYMENT_STATUS = 'APPROVED' AND p.PAYMENT_AMOUNT <> o.ORDER_AMOUNT)
      OR (p.PAYMENT_STATUS IN ('FAILED', 'CANCELLED') AND o.ORDER_STATUS IN ('PAID', 'READY_TO_SHIP'))
  )
ORDER BY p.PAID_AT DESC;
