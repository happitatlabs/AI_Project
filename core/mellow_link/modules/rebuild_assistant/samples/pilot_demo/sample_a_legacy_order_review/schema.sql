-- Demo schema for legacy order management modernization review.
-- The schema is intentionally small and simplified for upload-analysis demos.

CREATE TABLE LEGACY_CUSTOMER (
    CUSTOMER_ID        NUMBER(12)      PRIMARY KEY,
    CUSTOMER_NAME      VARCHAR2(100)   NOT NULL,
    CUSTOMER_GRADE     VARCHAR2(20)    NOT NULL,
    MOBILE_MASKED      VARCHAR2(30),
    EMAIL_MASKED       VARCHAR2(120),
    CREATED_AT         DATE           NOT NULL
);

COMMENT ON TABLE LEGACY_CUSTOMER IS '주문 고객 기본 정보';
COMMENT ON COLUMN LEGACY_CUSTOMER.CUSTOMER_ID IS '고객 식별자';
COMMENT ON COLUMN LEGACY_CUSTOMER.CUSTOMER_GRADE IS 'NORMAL, VIP 등 주문 조회 필터에 사용되는 고객 등급';

CREATE TABLE LEGACY_ORDER (
    ORDER_ID           NUMBER(12)      PRIMARY KEY,
    CUSTOMER_ID        NUMBER(12)      NOT NULL,
    ORDER_NO           VARCHAR2(30)    NOT NULL UNIQUE,
    ORDER_STATUS       VARCHAR2(20)    NOT NULL,
    ORDER_AMOUNT       NUMBER(15, 2)   NOT NULL,
    ORDERED_AT         DATE           NOT NULL,
    PAYMENT_DUE_AT     DATE,
    ADMIN_MEMO         VARCHAR2(1000),
    LAST_MODIFIED_BY   VARCHAR2(50),
    LAST_MODIFIED_AT   DATE,
    CONSTRAINT FK_LEGACY_ORDER_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID) REFERENCES LEGACY_CUSTOMER (CUSTOMER_ID)
);

COMMENT ON TABLE LEGACY_ORDER IS '주문 헤더. 상태 변경 이력 테이블 없이 현재 상태만 보관한다.';
COMMENT ON COLUMN LEGACY_ORDER.ORDER_STATUS IS 'RECEIVED, PAID, READY_TO_SHIP, SHIPPED, DELIVERED, CANCELLED';
COMMENT ON COLUMN LEGACY_ORDER.ADMIN_MEMO IS '관리자 수기 보정 사유가 자유 문장으로 남는 컬럼';

CREATE TABLE LEGACY_ORDER_ITEM (
    ORDER_ITEM_ID      NUMBER(12)      PRIMARY KEY,
    ORDER_ID           NUMBER(12)      NOT NULL,
    ITEM_CODE          VARCHAR2(40)    NOT NULL,
    ITEM_NAME          VARCHAR2(200)   NOT NULL,
    QUANTITY           NUMBER(10)      NOT NULL,
    UNIT_PRICE         NUMBER(15, 2)   NOT NULL,
    ITEM_STATUS        VARCHAR2(20)    NOT NULL,
    CONSTRAINT FK_LEGACY_ORDER_ITEM_ORDER
        FOREIGN KEY (ORDER_ID) REFERENCES LEGACY_ORDER (ORDER_ID)
);

COMMENT ON TABLE LEGACY_ORDER_ITEM IS '주문 품목. 주문 상태와 품목 상태가 별도 기준으로 갱신된다.';
COMMENT ON COLUMN LEGACY_ORDER_ITEM.ITEM_STATUS IS 'ORDERED, RESERVED, RELEASED, RETURN_REQUESTED';

CREATE TABLE LEGACY_PAYMENT (
    PAYMENT_ID         NUMBER(12)      PRIMARY KEY,
    ORDER_ID           NUMBER(12)      NOT NULL,
    PAYMENT_STATUS     VARCHAR2(20)    NOT NULL,
    PAYMENT_AMOUNT     NUMBER(15, 2)   NOT NULL,
    APPROVAL_NO        VARCHAR2(50),
    PAID_AT            DATE,
    CANCELLED_AT       DATE,
    INTERFACE_RESULT   VARCHAR2(20),
    INTERFACE_MESSAGE  VARCHAR2(500),
    CONSTRAINT FK_LEGACY_PAYMENT_ORDER
        FOREIGN KEY (ORDER_ID) REFERENCES LEGACY_ORDER (ORDER_ID)
);

COMMENT ON TABLE LEGACY_PAYMENT IS '결제 연계 결과. 주문 상태와 결제 상태 불일치가 발생할 수 있다.';
COMMENT ON COLUMN LEGACY_PAYMENT.PAYMENT_STATUS IS 'REQUESTED, APPROVED, FAILED, CANCELLED';
COMMENT ON COLUMN LEGACY_PAYMENT.INTERFACE_RESULT IS 'SUCCESS, RETRY, ERROR 등 외부 결제 연계 결과';

CREATE TABLE LEGACY_DELIVERY (
    DELIVERY_ID        NUMBER(12)      PRIMARY KEY,
    ORDER_ID           NUMBER(12)      NOT NULL,
    DELIVERY_STATUS    VARCHAR2(20)    NOT NULL,
    CARRIER_CODE       VARCHAR2(20),
    INVOICE_NO         VARCHAR2(60),
    READY_AT           DATE,
    SHIPPED_AT         DATE,
    DELIVERED_AT       DATE,
    RETRY_COUNT        NUMBER(5)       DEFAULT 0 NOT NULL,
    LAST_ERROR_MESSAGE VARCHAR2(500),
    CONSTRAINT FK_LEGACY_DELIVERY_ORDER
        FOREIGN KEY (ORDER_ID) REFERENCES LEGACY_ORDER (ORDER_ID)
);

COMMENT ON TABLE LEGACY_DELIVERY IS '배송 처리 상태. 결제 완료 이후 배송 준비와 출고 상태를 관리한다.';
COMMENT ON COLUMN LEGACY_DELIVERY.DELIVERY_STATUS IS 'WAITING, READY, SHIPPED, DELIVERED, HOLD';
COMMENT ON COLUMN LEGACY_DELIVERY.RETRY_COUNT IS '배송 연계 실패 후 재시도 횟수';

-- Relationship summary:
-- LEGACY_CUSTOMER 1:N LEGACY_ORDER
-- LEGACY_ORDER 1:N LEGACY_ORDER_ITEM
-- LEGACY_ORDER 1:1 or 1:N LEGACY_PAYMENT in practice, but the current schema does not enforce one approved payment.
-- LEGACY_ORDER 1:1 LEGACY_DELIVERY in normal operation, but exceptional orders may have missing delivery rows.
-- There is no dedicated order status history table in the current schema.
