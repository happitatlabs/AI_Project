--01 TN_FORINS
drop TABLE KOMIR_ERP.TN_FORINS;
CREATE TABLE KOMIR_ERP.TN_FORINS
(
ACCT_SEQ    VARCHAR2(50) Not Null, --계좌일련번호
TR_DATE     VARCHAR2(08) Not Null, --거래 이체일자
TR_DATE_SEQ   NUMBER(10) Not Null, --거래일자별일련번호
BANK_CD     VARCHAR2(07) Not Null, --금융기관코드
ACNT_NO     VARCHAR2(20) Not Null, --계좌번호
CHG_TIME    VARCHAR2(14) Not Null, --변경일시
IO_CD       VARCHAR2(01) Not Null, --입출금구분
MNEY_UNIT   VARCHAR2(05) ,  --화폐단위
EXCH_RATE     NUMBER(17,3), --환율 A = EXCH_RATE
I_FAMT        NUMBER(15,2), --외화입금액 B = FOREIGN_M
I_AMT         NUMBER(15) ,  --입금환산액 C=round(B*A)
O_FSUM        NUMBER(18,2), --외화출금누계 D=sum(I_FAMT) <--a외화출금
O_SUM         NUMBER(15) ,  --출금환산누계 E=sum(I_AMT) <--b원화출금
GAP_AMT       NUMBER(17,2), --환차 F=(C-E) 환차익 (거래후 원화잔액 / 거래후 외화잔액) * a
AVG_RATE      NUMBER(15,2), --평균출금환율 G=round(E/D)
CHIT_RMK    VARCHAR2(2000), --결의서적요
RMN_FAMT      NUMBER(18,2), --거래후 외화잔액 H = A-D
RMN_AMT       NUMBER(22) ,  --거래후 원화잔액 I = C-E
AC_DATE     VARCHAR2(08),   --전표일자
AC_CHITNO     NUMBER(04),   --전표번호
AUTO_YN     VARCHAR2(01) ,  --자동발생여부
UPD_EMP     VARCHAR2(08) ,  --수정자사번
UPD_DATE    VARCHAR2(14) )  --수정일시
TABLESPACE DATA_TS1 PCTFREE 20 INITRANS 1;

CREATE UNIQUE INDEX KOMIR_ERP.TN_FORINS0 ON KOMIR_ERP.TN_FORINS
(ACCT_SEQ, TR_DATE, TR_DATE_SEQ) TABLESPACE INDEX_TS2;

CREATE UNIQUE INDEX KOMIR_ERP.TN_FORINS1 ON KOMIR_ERP.TN_FORINS
(BANK_CD, ACNT_NO, TR_DATE, TR_DATE_SEQ) TABLESPACE INDEX_TS2;

ALTER TABLE KOMIR_ERP.TN_FORINS
ADD CONSTRAINT TN_FORINS0 PRIMARY KEY(ACCT_SEQ, TR_DATE, TR_DATE_SEQ);

COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.ACCT_SEQ IS '계좌일련번호';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.TR_DATE IS '거래 이체일자';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.TR_DATE_SEQ IS '거래일자별일련번호';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.BANK_CD IS '금융기관코드';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.ACNT_NO IS '계좌번호';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.CHG_TIME IS '변경일시';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.IO_CD IS '입출금구분';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.MNEY_UNIT IS '화폐단위';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.EXCH_RATE IS '환율';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.I_FAMT IS '외화입금액';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.I_AMT IS '입금환산액';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.O_FSUM IS '외화출금누계';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.O_SUM IS '출금환산누계';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.GAP_AMT IS '환차';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.AVG_RATE IS '평균출금환율';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.CHIT_RMK IS '결의서적요';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.RMN_FAMT IS '거래후 외화잔액';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.RMN_AMT IS '거래후 원화잔액';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.AC_DATE IS '전표일자';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.AC_CHITNO IS '전표번호';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.AUTO_YN IS '자동발생여부';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.UPD_EMP IS '수정자사번';
COMMENT ON COLUMN KOMIR_ERP.TN_FORINS.UPD_DATE IS '수정일시';
COMMENT ON TABLE KOMIR_ERP.TN_FORINS IS '외화입금내역';

