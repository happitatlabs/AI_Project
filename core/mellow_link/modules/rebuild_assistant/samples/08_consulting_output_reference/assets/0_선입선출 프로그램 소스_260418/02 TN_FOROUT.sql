--02 TN_FOROUT
drop table TN_FOROUT;
CREATE TABLE KOMIR_ERP.TN_FOROUT
(
BANK_CD     VARCHAR2(07) NOT NULL, -- 금융기관코드
ACNT_NO     VARCHAR2(20) NOT NULL, -- 계좌번호
TR_DATE     VARCHAR2(08) NOT NULL, -- 거래 이체일자 --> ACCOUNTING_DATE
TR_DATE_SEQ   NUMBER(10) NOT NULL, -- 거래일자별일련번호
ACCT_SEQ    VARCHAR2(50),   -- 계좌일련번호
MNEY_UNIT   VARCHAR2(05),   -- 화폐단위
OUTF_AMT      NUMBER(15,2), -- 외화출금액 A
EXCH_RATE     NUMBER(17,3), -- 환율 B
OUT_AMT       NUMBER(15),   -- 출금액 C=A*B --------------
OUT_SUM       NUMBER(15),   -- 출금누계*
GAP_SUM       NUMBER(15),   -- 환차누계*
AC_DATE     VARCHAR2(08),   -- 전표일자
AC_CHITNO     NUMBER(04),   -- 전표번호
UPD_EMP     VARCHAR2(08),   -- 수정자사번
UPD_DATE    VARCHAR2(14)    -- 수정일시
)
TABLESPACE DATA_TS1
PCTFREE 20
INITRANS 1;

CREATE UNIQUE INDEX KOMIR_ERP.TN_FOROUT0
ON KOMIR_ERP.TN_FOROUT
(BANK_CD, ACNT_NO, TR_DATE, TR_DATE_SEQ)
TABLESPACE INDEX_TS2;

CREATE INDEX KOMIR_ERP.TN_FOROUT1
ON KOMIR_ERP.TN_FOROUT
(ACCT_SEQ, TR_DATE, TR_DATE_SEQ)
TABLESPACE INDEX_TS2;

ALTER TABLE KOMIR_ERP.TN_FOROUT
ADD CONSTRAINT TN_FOROUT0 PRIMARY KEY(BANK_CD, ACNT_NO, TR_DATE, TR_DATE_SEQ);

COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.BANK_CD IS '금융기관코드';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.ACNT_NO IS '계좌번호';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.TR_DATE IS '거래이체일자';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.TR_DATE_SEQ IS '거래일자별일련번호';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.ACCT_SEQ IS '계좌일련번호';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.MNEY_UNIT IS '화폐단위';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.OUTF_AMT IS '외화출금액';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.EXCH_RATE IS '환율';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.OUT_AMT IS '출금액';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.OUT_SUM IS '출금누계';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.GAP_SUM IS '환차누계';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.AC_DATE IS '전표일자';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.AC_CHITNO IS '전표번호';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.UPD_EMP IS '수정자사번';
COMMENT ON COLUMN KOMIR_ERP.TN_FOROUT.UPD_DATE IS '수정일시';
COMMENT ON TABLE KOMIR_ERP.TN_FOROUT IS '외화출금내역';

drop synonym FOROUT;
create synonym FOROUT for TN_FOROUT;
