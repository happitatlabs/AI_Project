CREATE TABLE TN_FOROUD (
    BANK_CD VARCHAR2(10),
    ACNT_NO VARCHAR2(30),
    OUT_DATE VARCHAR2(8),
    OUT_DATE_SEQ NUMBER,
    IN_DATE VARCHAR2(8),
    IN_DATE_SEQ NUMBER,
    OUTF_AMT NUMBER,
    OUT_AMT0 NUMBER,
    GAP_AMT NUMBER,
    MNEY_UNIT VARCHAR2(5)
);

CREATE INDEX TN_FOROUD1 ON TN_FOROUD (BANK_CD, ACNT_NO, OUT_DATE, OUT_DATE_SEQ);
