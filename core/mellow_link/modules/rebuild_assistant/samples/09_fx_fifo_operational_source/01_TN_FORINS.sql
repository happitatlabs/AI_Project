CREATE TABLE TN_FORINS (
    ACCT_SEQ VARCHAR2(50),
    TR_DATE VARCHAR2(8),
    TR_DATE_SEQ NUMBER,
    MNEY_UNIT VARCHAR2(5),
    EXCH_RATE NUMBER,
    I_FAMT NUMBER,
    I_AMT NUMBER,
    GAP_AMT NUMBER,
    RMN_FAMT NUMBER,
    RMN_AMT NUMBER,
    AC_DATE VARCHAR2(8),
    AC_CHITNO VARCHAR2(20)
);

CREATE UNIQUE INDEX TN_FORINS0 ON TN_FORINS (ACCT_SEQ, TR_DATE, TR_DATE_SEQ);
